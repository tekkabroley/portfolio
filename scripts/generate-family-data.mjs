#!/usr/bin/env node
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");
const FAMILY_DIR = path.join(ROOT, "src/content/family");
const OUT_DIR = path.join(ROOT, "functions/_data");
const OUT_FILE = path.join(OUT_DIR, "family-photos.js");

function parseFrontmatter(content) {
  const match = content.match(/^---\r?\n([\s\S]*?)\r?\n---/);
  if (!match) return {};

  const data = {};
  for (const line of match[1].split("\n")) {
    const colonIdx = line.indexOf(":");
    if (colonIdx === -1) continue;
    const key = line.slice(0, colonIdx).trim();
    const value = line.slice(colonIdx + 1).trim();
    data[key] = value;
  }
  return data;
}

function imageUrlToFamilyPath(image) {
  if (!image) return null;

  try {
    if (image.startsWith("s3://")) {
      const withoutScheme = image.slice("s3://".length);
      const slash = withoutScheme.indexOf("/");
      if (slash === -1) return null;
      return withoutScheme.slice(slash + 1);
    }

    const url = new URL(image);
    return url.pathname.replace(/^\/+/, "");
  } catch {
    if (image.startsWith("family/")) return image;
    return null;
  }
}

function main() {
  if (!fs.existsSync(FAMILY_DIR)) {
    throw new Error(`Missing family content directory: ${FAMILY_DIR}`);
  }

  const files = fs
    .readdirSync(FAMILY_DIR)
    .filter((name) => name.endsWith(".md"))
    .sort();

  const allowlist = [];
  const photos = [];

  for (const file of files) {
    const content = fs.readFileSync(path.join(FAMILY_DIR, file), "utf8");
    const data = parseFrontmatter(content);
    const familyPath = imageUrlToFamilyPath(data.image);

    if (!familyPath || !familyPath.startsWith("family/")) {
      console.warn(`Skipping ${file}: could not derive family/ S3 path`);
      continue;
    }

    if (!allowlist.includes(familyPath)) {
      allowlist.push(familyPath);
    }

    photos.push({
      path: familyPath,
      alt: data.title || "Family photo",
    });
  }

  allowlist.sort();
  photos.sort((a, b) => a.path.localeCompare(b.path));

  fs.mkdirSync(OUT_DIR, { recursive: true });
  const body = `// Generated by scripts/generate-family-data.mjs - do not edit by hand.
export const allowlist = ${JSON.stringify(allowlist, null, 2)};

export const photos = ${JSON.stringify(photos, null, 2)};
`;
  fs.writeFileSync(OUT_FILE, `${body}\n`, "utf8");

  console.log(
    `Wrote ${photos.length} family photo(s) to ${path.relative(ROOT, OUT_FILE)}`,
  );
}

main();
